/** First guess at line start times: spread lines over the song, longer lines get more time,
    with room for the intro, outro and section breaks. */
export function estimateTimes(lines: Line[], dur: number): number[] {
  const intro = Math.min(12, dur * 0.08), outro = Math.min(10, dur * 0.06);
  let prevSec: string | null = null;
  const w = lines.map(l => { const gap = l.sec !== prevSec ? 4 : 0; prevSec = l.sec; return gap + 3 + l.t.replace(/[\s፣!።]/g, "").length; });
  const total = w.reduce((a, b) => a + b, 0), span = dur - intro - outro;
  let acc = 0;
  return w.map((x, i) => {
    const gap = i === 0 || lines[i].sec !== lines[i - 1].sec ? 4 : 0;
    const t = intro + ((acc + gap) / total) * span; acc += x;
    return +t.toFixed(2);
  });
}

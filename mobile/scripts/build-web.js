// Builds the browser version into ../app, served by GitHub Pages at
// https://bazinmelesse.github.io/fedel-game/app/ and made to work offline with a service worker.
// Run: npm run build:web   (then commit the ../app folder)
const { execSync } = require("child_process");
const crypto = require("crypto");
const fs = require("fs");
const path = require("path");

const out = path.resolve(__dirname, "..", "..", "app");
fs.rmSync(out, { recursive: true, force: true });
execSync(`npx expo export --platform web --output-dir "${out}"`, { stdio: "inherit", cwd: path.resolve(__dirname, "..") });

// Every file in the build, relative to the app folder
const files = [];
(function walk(dir) {
  for (const f of fs.readdirSync(dir)) {
    const p = path.join(dir, f);
    if (fs.statSync(p).isDirectory()) walk(p);
    else files.push(path.relative(out, p).split(path.sep).join("/"));
  }
})(out);
const hash = crypto.createHash("sha1");
files.sort().forEach(f => hash.update(f).update(fs.readFileSync(path.join(out, f))));
const version = hash.digest("hex").slice(0, 10);

// Service worker: saves the whole game on the first visit, then plays from the saved copy with no internet
const urls = ["./", ...files.filter(f => f !== "index.html" && f !== "metadata.json").map(f => "./" + f)];
fs.writeFileSync(path.join(out, "sw.js"), `// Generated by mobile/scripts/build-web.js
const CACHE = "fidel-app-${version}";
const FILES = ${JSON.stringify(urls, null, 1)};
self.addEventListener("install", e => {
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES)).then(() => self.skipWaiting()));
});
self.addEventListener("activate", e => {
  e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k.startsWith("fidel-app-") && k !== CACHE).map(k => caches.delete(k))))
    .then(() => self.clients.claim()));
});
self.addEventListener("fetch", e => {
  if (e.request.method !== "GET") return;
  const url = new URL(e.request.url);
  const key = e.request.mode === "navigate" ? new URL("./", self.registration.scope).href : url.href;
  e.respondWith(caches.match(key, { ignoreSearch: true }).then(hit => hit || fetch(e.request)));
});
`);

fs.writeFileSync(path.join(out, "manifest.json"), JSON.stringify({
  name: "ፊደል ጨዋታ · Fidel Game", short_name: "ፊደል", start_url: "./", scope: "./", display: "standalone",
  orientation: "any", background_color: "#fff8e7", theme_color: "#2e7d5b",
  icons: [{ src: "icon.png", sizes: "1024x1024", type: "image/png", purpose: "any maskable" }],
}, null, 2));
fs.copyFileSync(path.resolve(__dirname, "..", "assets", "icon.png"), path.join(out, "icon.png"));

// Register the service worker and the install manifest, and reload once when a new version arrives
let html = fs.readFileSync(path.join(out, "index.html"), "utf8");
html = html.replace("</head>", `<link rel="manifest" href="manifest.json"/><meta name="theme-color" content="#2e7d5b"/><link rel="apple-touch-icon" href="icon.png"/></head>`);
html = html.replace("</body>", `<script>
if ("serviceWorker" in navigator) {
  var had = !!navigator.serviceWorker.controller;
  navigator.serviceWorker.addEventListener("controllerchange", function () { if (had && !window.__r) { window.__r = 1; location.reload(); } });
  navigator.serviceWorker.register("sw.js", { updateViaCache: "none" }).then(function (r) { r.update(); }).catch(function () {});
}
</script></body>`);
fs.writeFileSync(path.join(out, "index.html"), html);
console.log(`Built ${files.length} files into ${out} (version ${version})`);

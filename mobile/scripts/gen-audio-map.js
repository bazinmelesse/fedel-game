// Writes src/audio/clips.ts: a static require() for every recording in ../audio and ../audio/num,
// so Metro bundles them into the app and they play with no internet.
// Run again after adding or re-recording clips: npm run gen:audio
const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..", "..");
const letters = fs.readdirSync(path.join(root, "audio")).filter(f => /^[0-9a-f]{4}\.mp3$/.test(f)).sort();
const nums = fs.readdirSync(path.join(root, "audio", "num")).filter(f => /^\d+\.mp3$/.test(f))
  .sort((a, b) => parseInt(a) - parseInt(b));

const out = [
  "// Generated by scripts/gen-audio-map.js. Do not edit by hand.",
  "",
  "/** Letter clips keyed by Unicode code point, e.g. 0x1200 for ሀ. */",
  "export const LETTER_CLIPS: Record<number, number> = {",
  ...letters.map(f => `  0x${f.slice(0, 4)}: require("../../../audio/${f}"),`),
  "};",
  "",
  "/** Number clips keyed by value, e.g. 23 for ፳፫. */",
  "export const NUMBER_CLIPS: Record<number, number> = {",
  ...nums.map(f => `  ${parseInt(f)}: require("../../../audio/num/${f}"),`),
  "};",
  "",
];
fs.writeFileSync(path.join(__dirname, "..", "src", "audio", "clips.ts"), out.join("\n"));
console.log(`clips.ts: ${letters.length} letters, ${nums.length} numbers`);
